// 일본어 원문(한자+가나)과 로마자(또는 히라가나) 전체 발음을 가나 앵커(Kana-Anchor)로 정렬하여 사전에 없는 모든 한자의 후리가나를 자동 추출·등록
export function registerDynamicKanjiReadings(
  jpText: string,
  romajiText: string
): void {
  if (!jpText || !romajiText || !containsKanji(jpText)) return;
  const fullHira = romajiToHiragana(romajiText);
  if (!fullHira) return;

  // jpText를 [한자 덩어리]와 [비한자(가나/기호) 덩어리] 토큰으로 분리
  interface Token {
    isKanji: boolean;
    raw: string;
    cleanHira: string;
  }
  const tokens: Token[] = [];
  const regex = /([\u4e00-\u9faf\u3400-\u4dbf]+)|([^\u4e00-\u9faf\u3400-\u4dbf]+)/g;
  let m: RegExpExecArray | null;
  while ((m = regex.exec(jpText)) !== null) {
    if (m[1]) {
      tokens.push({ isKanji: true, raw: m[1], cleanHira: '' });
    } else if (m[2]) {
      const hiraOnly = katakanaToHiragana(m[2]).replace(
        /[^\u3041-\u3096]/g,
        ''
      );
      tokens.push({ isKanji: false, raw: m[2], cleanHira: hiraOnly });
    }
  }

  let hiraCursor = 0;
  let updated = false;

  for (let idx = 0; idx < tokens.length; idx++) {
    const tok = tokens[idx];
    if (!tok.isKanji) {
      if (tok.cleanHira) {
        const foundAt = fullHira.indexOf(tok.cleanHira, hiraCursor);
        if (foundAt !== -1 && foundAt - hiraCursor <= 12) {
          hiraCursor = foundAt + tok.cleanHira.length;
        }
      }
      continue;
    }

    // 다음 비한자 가나 앵커 찾기
    let nextAnchor = '';
    for (let j = idx + 1; j < tokens.length; j++) {
      if (!tokens[j].isKanji && tokens[j].cleanHira) {
        nextAnchor = tokens[j].cleanHira;
        break;
      }
    }

    if (nextAnchor) {
      // 한자 최소 1글자 이상 뒤에서 nextAnchor 위치 탐색 (조사 は->わ 변형 고려)
      const anchorVariants = [nextAnchor];
      if (nextAnchor.startsWith('は')) {
        anchorVariants.push('わ' + nextAnchor.slice(1));
      }
      if (nextAnchor.startsWith('を')) {
        anchorVariants.push('お' + nextAnchor.slice(1));
      }

      let bestPos = -1;
      for (const variant of anchorVariants) {
        const pos = fullHira.indexOf(variant, hiraCursor + 1);
        if (pos !== -1 && pos - hiraCursor <= tok.raw.length * 5 + 2) {
          if (bestPos === -1 || pos < bestPos) {
            bestPos = pos;
          }
        }
      }

      if (bestPos !== -1) {
        const extractedReading = fullHira.slice(hiraCursor, bestPos);
        if (extractedReading && /^[ぁ-んー]+$/.test(extractedReading)) {
          DYNAMIC_RUBY_MAP.set(tok.raw, extractedReading);
          updated = true;
        }
        hiraCursor = bestPos;
      }
    } else {
      // 문장 끝의 한자 블록
      const extractedReading = fullHira.slice(hiraCursor);
      if (
        extractedReading &&
        extractedReading.length <= tok.raw.length * 5 &&
        /^[ぁ-んー]+$/.test(extractedReading)
      ) {
        DYNAMIC_RUBY_MAP.set(tok.raw, extractedReading);
        updated = true;
      }
    }
  }

  if (updated) {
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(
          DYNAMIC_RUBY_STORAGE_KEY,
          JSON.stringify(Array.from(DYNAMIC_RUBY_MAP.entries()))
        );
      }
    } catch {
      // ignore
    }
  }
}

function appendPlainTextSegment(segments: RubySegment[], text: string): void {
  if (!text) return;
  if (segments.length > 0 && !segments[segments.length - 1].furigana) {
    segments[segments.length - 1].text += text;
  } else {
    segments.push({ text });
  }
}

// 일본어 문장을 분석하여 한자 단어 바로 위에만 후리가나(<ruby>)를 올릴 수 있도록 세그먼트로 분리하는 함수
export function parseJapaneseToRubySegments(jpText: string): RubySegment[] {
  if (!jpText) return [];
  const segments: RubySegment[] = [];
  const dict = getCombinedSortedRubyDict();
  let i = 0;

  while (i < jpText.length) {
    let matched = false;

    // 현재 위치에서 사전(동적 학습 사전 + 내장 사전)의 한자 어휘와 일치하는지 확인
    for (const [kanjiWord, reading] of dict) {
      if (jpText.startsWith(kanjiWord, i)) {
        if (containsKanji(kanjiWord)) {
          // 앞/뒤에 공유되는 히라가나/가타카나(예: お会計 -> お + 会計, 食べて -> 食 + べて)를 분리하여 한자 위에만 루비를 얹음
          const normWord = katakanaToHiragana(kanjiWord);
          const normReading = katakanaToHiragana(reading);

          let prefixLen = 0;
          while (
            prefixLen < kanjiWord.length &&
            prefixLen < reading.length &&
            !containsKanji(kanjiWord[prefixLen]) &&
            normWord[prefixLen] === normReading[prefixLen]
          ) {
            prefixLen++;
          }

          let suffixLen = 0;
          while (
            suffixLen < kanjiWord.length - prefixLen &&
            suffixLen < reading.length - prefixLen &&
            !containsKanji(kanjiWord[kanjiWord.length - 1 - suffixLen]) &&
            normWord[kanjiWord.length - 1 - suffixLen] ===
              normReading[reading.length - 1 - suffixLen]
          ) {
            suffixLen++;
          }

          const prefixText = kanjiWord.slice(0, prefixLen);
          const coreText = kanjiWord.slice(prefixLen, kanjiWord.length - suffixLen);
          const coreReading = reading.slice(prefixLen, reading.length - suffixLen);
          const suffixText = kanjiWord.slice(kanjiWord.length - suffixLen);

          appendPlainTextSegment(segments, prefixText);
          if (coreText && containsKanji(coreText)) {
            segments.push({ text: coreText, furigana: coreReading });
          } else {
            appendPlainTextSegment(segments, coreText);
          }
          appendPlainTextSegment(segments, suffixText);
        } else {
          appendPlainTextSegment(segments, kanjiWord);
        }
        i += kanjiWord.length;
        matched = true;
        break;
      }
    }

    if (!matched) {
      appendPlainTextSegment(segments, jpText[i]);
      i++;
    }
  }

  return segments;
}

// 일본어 문장(한자+가나) 전체를 히라가나 읽기로 변환
export function japaneseToHiraganaReading(jpText: string): string {
  const segments = parseJapaneseToRubySegments(jpText);
  const joined = segments.map((seg) => seg.furigana || seg.text).join('');
  return katakanaToHiragana(joined);
}

