function addBatchimToHangul(hangulChar: string, batchimType: 'ㅅ' | 'ㄴ'): string {
  const code = hangulChar.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return hangulChar;
  const offset = code - 0xac00;
  const jong = offset % 28;
  if (jong !== 0) return hangulChar;
  const addJong = batchimType === 'ㄴ' ? 4 : 19;
  return String.fromCharCode(code + addJong);
}

export function kanaToKoreanPronunciation(inputText: string): string {
  const hira = japaneseToHiraganaReading(inputText);
  const out: string[] = [];
  let i = 0;

  while (i < hira.length) {
    const ch = hira[i];
    const next = hira[i + 1] || '';
    const two = ch + next;

    if (ch === 'っ') {
      if (out.length > 0) {
        out[out.length - 1] = addBatchimToHangul(out[out.length - 1], 'ㅅ');
      }
      i++;
      continue;
    }

    if (ch === 'ん') {
      if (out.length > 0) {
        const prev = out[out.length - 1];
        const modified = addBatchimToHangul(prev, 'ㄴ');
        if (modified !== prev) {
          out[out.length - 1] = modified;
          i++;
          continue;
        }
      }
      out.push('응');
      i++;
      continue;
    }

    // 조사 は -> 와 처리 (어두가 아니며 はい/はし/はな/はら/はや/はき/はん 등 어휘 내부가 아닐 때)
    if (
      ch === 'は' &&
      i > 0 &&
      hira[i - 1] !== '、' &&
      hira[i - 1] !== '。' &&
      hira[i - 1] !== ' ' &&
      hira[i - 1] !== 'お' &&
      hira[i - 1] !== 'ご' &&
      !['い', 'し', 'な', 'ら', 'や', 'き', 'ん', 'っ', 'こ', 'ち', 'ず'].includes(next)
    ) {
      out.push('와');
      i++;
      continue;
    }

    if (DIGRAPH_KANA_MAP[two]) {
      out.push(DIGRAPH_KANA_MAP[two]);
      i += 2;
      continue;
    }

    if (MONOGRAPH_KANA_MAP[ch]) {
      out.push(MONOGRAPH_KANA_MAP[ch]);
      i++;
      continue;
    }

    out.push(ch);
    i++;
  }

  return out.join('').replace(/\s+/g, ' ').trim();
}

