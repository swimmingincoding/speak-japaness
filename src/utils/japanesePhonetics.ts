try {
  if (typeof localStorage !== 'undefined') {
    const raw = localStorage.getItem(DYNAMIC_RUBY_STORAGE_KEY);
    if (raw) {
      const pairs: Array<[string, string]> = JSON.parse(raw);
      for (const [k, v] of pairs) {
        if (k && v) DYNAMIC_RUBY_MAP.set(k, v);
      }
    }
  }
} catch {
  // ignore
}

function getCombinedSortedRubyDict(): Array<[string, string]> {
  const dynamicEntries = Array.from(DYNAMIC_RUBY_MAP.entries());
  return [...dynamicEntries, ...KANJI_RUBY_DICT]
    .map(([k, v]): [string, string] => [k.trim(), v.trim()])
    .filter(([k, v]) => k && v)
    .sort((a, b) => b[0].length - a[0].length);
}

function containsKanji(str: string): boolean {
  return /[\u4e00-\u9faf\u3400-\u4dbf]/.test(str);
}

// 가타카나를 히라가나로 변환
export function katakanaToHiragana(str: string): string {
  return str.replace(/[\u30a1-\u30f6]/g, (match) => {
    const chr = match.charCodeAt(0) - 0x60;
    return String.fromCharCode(chr);
  });
}

